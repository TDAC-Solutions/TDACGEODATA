import { useEffect, useMemo, useState } from "react";
import {
  getSampleRegister,
  type SamplingRecord,
  type SoilRecord,
} from "../../../../api/fieldData";
import { getProjectLocas, type LocaRecord } from "../../../../api/projects";
import { QrCodeModal } from "./QrCodeModal";

interface SampleRegisterTabProps {
  projectId: string;
}

/**
 * Sample Register (Lab Data).
 *
 * Moved from Field Data -> "Sampling / Coring", where it was a view-only list
 * of approved Soil (SPT) and Rock (coring) samples for ONE location. Lab Data is
 * project-scoped, so this adds a Location filter and, on "All Locations", a
 * Location column. The rows, columns and APPROVED-only rule are unchanged, and
 * the Sample IDs are the same ones the Field Data workflows generated.
 *
 * Nothing here creates, edits or deletes. The SPT and Rock tabs in Field Data
 * remain the workflows that produce these rows and the admin approvals that
 * publish them -- moving those would break submit -> PENDING -> approve.
 *
 * One request for the whole project, narrowed server-side by the filter,
 * rather than one request per borehole.
 */
export function SampleRegisterTab({ projectId }: SampleRegisterTabProps) {
  const [locas, setLocas] = useState<LocaRecord[]>([]);
  const [locasLoading, setLocasLoading] = useState(true);
  const [locasError, setLocasError] = useState<string | null>(null);

  const [selectedLocation, setSelectedLocation] = useState<string>("ALL");
  const [activeView, setActiveView] = useState<"soil" | "rock">("rock");

  const [qrOpen, setQrOpen] = useState(false);

  const [rockRecords, setRockRecords] = useState<SamplingRecord[]>([]);
  const [soilRecords, setSoilRecords] = useState<SoilRecord[]>([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);

  // --- Locations -----------------------------------------------------------
  useEffect(() => {
    let cancelled = false;

    async function load() {
      try {
        setLocasLoading(true);
        setLocasError(null);

        const data = await getProjectLocas(projectId);

        if (!cancelled) {
          setLocas(data);
        }
      } catch (err) {
        if (!cancelled) {
          setLocasError(
            err instanceof Error
              ? err.message
              : "Unable to load investigation locations."
          );
        }
      } finally {
        if (!cancelled) {
          setLocasLoading(false);
        }
      }
    }

    load();

    return () => {
      cancelled = true;
    };
  }, [projectId]);

  // --- Register ------------------------------------------------------------
  useEffect(() => {
    let cancelled = false;

    async function load() {
      try {
        setLoading(true);
        setError(null);

        const register = await getSampleRegister(
          projectId,
          selectedLocation === "ALL" ? undefined : selectedLocation
        );

        if (!cancelled) {
          setSoilRecords(register.soil);
          setRockRecords(register.rock);
        }
      } catch (err) {
        if (!cancelled) {
          setError(
            err instanceof Error
              ? err.message
              : "Unable to load the sample register."
          );
        }
      } finally {
        if (!cancelled) {
          setLoading(false);
        }
      }
    }

    load();

    return () => {
      cancelled = true;
    };
  }, [projectId, selectedLocation]);

  const locationOptions = useMemo(
    () => [...new Set(locas.map((loca) => loca.loca_id))].sort(),
    [locas]
  );

  /* The Location column only earns its place when the rows come from more than
     one borehole; on a single location the filter already says which. */
  const showLocationColumn = selectedLocation === "ALL";

  return (
    <div>
      <div className="module-toolbar">
        <div>
          <h3 className="panel-subtitle">Sample Register</h3>
          <p className="page-sub">
            Approved soil (SPT) and rock (coring) samples registered for this
            project. Samples are generated by the field workflows in Field Data
            and appear here once approved.
          </p>
        </div>

        {/* Same filter control as the Test Register, as a single column. */}
        <div className="sample-register-filters">
          <label>
            <span>Location / Borehole</span>
            <select
              value={selectedLocation}
              onChange={(event) => setSelectedLocation(event.target.value)}
              disabled={locasLoading || locationOptions.length === 0}
            >
              <option value="ALL">All Locations</option>
              {locationOptions.map((locaId) => (
                <option key={locaId} value={locaId}>
                  {locaId}
                </option>
              ))}
            </select>
          </label>

          {/* Opens on the register's current borehole filter, so a narrowed
              view does not lose its context. */}
          <button
            type="button"
            className="btn btn-sm"
            onClick={() => setQrOpen(true)}
            disabled={loading || (soilRecords.length === 0 && rockRecords.length === 0)}
            title={
              loading
                ? "Loading the sample register\u2026"
                : soilRecords.length === 0 && rockRecords.length === 0
                  ? "No approved samples to print yet"
                  : `Generate QR codes for this project's ${activeView} samples`
            }
          >
            Generate QR codes
          </button>
        </div>
      </div>

      <div className="sampling-view-tabs">
        <button
          type="button"
          className={`sampling-view-tab ${activeView === "soil" ? "active" : ""}`}
          onClick={() => setActiveView("soil")}
        >
          Soil
        </button>
        <button
          type="button"
          className={`sampling-view-tab ${activeView === "rock" ? "active" : ""}`}
          onClick={() => setActiveView("rock")}
        >
          Rock
        </button>
      </div>

      {locasLoading || loading ? (
        <p className="page-sub">Loading sample register…</p>
      ) : locasError ? (
        <p className="page-sub field-error">{locasError}</p>
      ) : error ? (
        <p className="page-sub field-error">{error}</p>
      ) : activeView === "soil" ? (
        soilRecords.length === 0 ? (
          <div className="empty-state">
            <h3>No approved Soil data</h3>
            <p>
              Soil records come from approved SPT data. Submit SPT rows in Field
              Data and have an admin approve them to see them here.
            </p>
          </div>
        ) : (
          <div className="table-scroll">
            <table className="dtable sample-register-table">
              <thead>
                <tr>
                  <th>Sample ID</th>
                  {showLocationColumn && <th>Location</th>}
                  <th>Depth (m)</th>
                  <th>Blows @15cm</th>
                  <th>Blows @30cm</th>
                  <th>Blows @45cm</th>
                  <th>SPT N-value</th>
                  <th>Created By</th>
                </tr>
              </thead>
              <tbody>
                {soilRecords.map((record) => (
                  <tr key={`${record.loca_id}-${record.sample_id}`}>
                    <td className="sample-id-cell" data-label="Sample ID">
                      {record.sample_id}
                    </td>
                    {showLocationColumn && (
                      <td data-label="Location">{record.loca_id}</td>
                    )}
                    <td className="num" data-label="Depth (m)">
                      {formatNumber(record.depth_from)}
                    </td>
                    <td className="num" data-label="Blows @15cm">
                      {formatNumber(record.blows_15)}
                    </td>
                    <td className="num" data-label="Blows @30cm">
                      {formatNumber(record.blows_30)}
                    </td>
                    <td className="num" data-label="Blows @45cm">
                      {formatNumber(record.blows_45)}
                    </td>
                    <td className="num" data-label="SPT N-value">
                      {formatNumber(record.n_value)}
                    </td>
                    <td className="cell-dim" data-label="Created By">
                      {record.created_by || "—"}
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        )
      ) : rockRecords.length === 0 ? (
        <div className="empty-state">
          <h3>No approved Rock data</h3>
          <p>
            Rock records come from approved Rock runs. Submit runs in the Field
            Data Rock tab and have an admin approve them to see them here.
          </p>
        </div>
      ) : (
        <div className="table-scroll">
          <table className="dtable sample-register-table">
            <thead>
              <tr>
                <th>Sample ID</th>
                {showLocationColumn && <th>Location</th>}
                <th>Run Depth From (m)</th>
                <th>Run Depth To (m)</th>
                <th>Recovery (%)</th>
                <th>RQD (%)</th>
                <th>Type of Rock</th>
                <th>Lift No</th>
                <th>Created By</th>
              </tr>
            </thead>
            <tbody>
              {rockRecords.map((record) => (
                <tr key={`${record.loca_id}-${record.sample_id}`}>
                  <td className="sample-id-cell" data-label="Sample ID">
                    {record.sample_id}
                  </td>
                  {showLocationColumn && (
                    <td data-label="Location">{record.loca_id}</td>
                  )}
                  <td className="num" data-label="Run Depth From (m)">
                    {formatNumber(record.depth_from)}
                  </td>
                  <td className="num" data-label="Run Depth To (m)">
                    {formatNumber(record.depth_to)}
                  </td>
                  <td className="num" data-label="Recovery (%)">
                    {formatNumber(record.recovery)}
                  </td>
                  <td className="num" data-label="RQD (%)">
                    {formatNumber(record.rqd)}
                  </td>
                  <td data-label="Type of Rock">
                    {formatNumber(record.rock_description)}
                  </td>
                  <td data-label="Lift No">
                    {formatNumber(record.lift_no)}
                  </td>
                  <td className="cell-dim" data-label="Created By">
                    {record.created_by || "—"}
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      )}

      {qrOpen && (
        <QrCodeModal
          projectId={projectId}
          locas={locas}
          initialLocaId={selectedLocation}
          initialScope={activeView}
          onClose={() => setQrOpen(false)}
        />
      )}
    </div>
  );
}

function formatNumber(value: number | string | null | undefined): string {
  return value === null || value === undefined || value === ""
    ? "—"
    : String(value);
}