/**
 * Field Data > Rock. Same workflow as SptModule:
 *   submit -> PENDING -> admin Approve / Reject, Sample ID generated by the
 *   shared backend generator, creator/editor/approver and field-level history
 *   kept by the existing audit trail.
 *
 * Columns: Run Depth From (CORE_TOP), Run Depth To (CORE_BASE),
 * Type of Rock (GEOL_DESC) and Lift No (TDAC-specific).
 *
 * Recovery and RQD are DERIVED, not typed. Each core piece is entered in its
 * own "Block Number" box and the server works the two percentages out from
 * them, so a stored value cannot disagree with the lengths it came from. The
 * formulas are mirrored here purely so the boxes can show a live preview; the
 * server recomputes and wins.
 *
 *   Recovery (%) = sum(piece lengths) / run length * 100
 *   RQD (%)      = sum(pieces >= 10 cm) / run length * 100
 *
 * Depths are metres and pieces are entered in centimetres by default, so the
 * run length is converted to centimetres before it shares a denominator with
 * the pieces. Getting that wrong is a factor of 100, not a rounding nit.
 */

/** The standard minimum sound piece length that counts towards RQD. */
const RQD_MIN_PIECE_CM = 10;

const CM_PER_M = 100;

/** Guard the "+ piece" button against a runaway paste. Matches the server. */
const MAX_PIECES = 100;

interface RockModuleProps {
  projectId: string;
  locaId: string;
}

/** All values are held as text so a half-typed number survives a re-render. */
interface RockDraft {
  depth_from: string;
  depth_to: string;
  rock_type: string;
  lift_no: string;
  /** One entry per Block Number, in entry order, in `pieceUnit`. */
  pieces: string[];
}

const EMPTY_DRAFT: RockDraft = {
  depth_from: "",
  depth_to: "",
  rock_type: "",
  lift_no: "",
  pieces: [],
};

const INITIAL_GRID_ROWS = 3;

/** Mirror of the server's unit conversion, for the live preview only. */
function toCentimetres(value: string, unit: PieceUnit): number | null {
  const trimmed = value.trim();
  if (trimmed === "") return null;
  const n = Number(trimmed);
  if (!Number.isFinite(n) || n < 0) return null;
  return unit === "m" ? n * CM_PER_M : n;
}

/** Render a stored centimetre value in whatever unit is on screen. */
function fromCentimetres(valueCm: number, unit: PieceUnit): string {
  const n = unit === "m" ? valueCm / CM_PER_M : valueCm;
  // Trim the float noise the conversion introduces without lying about it.
  return String(Math.round(n * 1e6) / 1e6);
}

/**
 * Live Recovery / RQD for the boxes on screen.
 *
 * Returns nulls while the run is incomplete rather than showing a wrong
 * number, and `oversized` when the pieces are longer than the run itself,
 * which is the one state worth warning about before submission.
 */
function previewMetrics(
  draft: RockDraft,
  unit: PieceUnit
): { recovery: string; rqd: string; qualifying: number; total: number; oversized: boolean } {
  const from = Number(draft.depth_from);
  const to = Number(draft.depth_to);
  const blank = { recovery: "—", rqd: "—", qualifying: 0, total: 0, oversized: false };

  if (draft.depth_from.trim() === "" || draft.depth_to.trim() === "") return blank;
  if (!Number.isFinite(from) || !Number.isFinite(to) || to <= from) return blank;

  const piecesCm = draft.pieces
    .map((piece) => toCentimetres(piece, unit))
    .filter((piece): piece is number => piece !== null);

  const runCm = (to - from) * CM_PER_M;
  const total = piecesCm.reduce((sum, piece) => sum + piece, 0);
  const qualifying = piecesCm.filter((piece) => piece >= RQD_MIN_PIECE_CM)
    .length;

  const pct = (part: number) =>
    runCm > 0 ? ((part / runCm) * 100).toFixed(2) : "—";

  const oversized = total > runCm;

  // Showing an impossible number (386.67%) in a cell labelled "Recovery (%)"
  // is worse than showing nothing, even with the warning underneath. The row
  // cannot be submitted anyway.
  if (oversized) {
    return {
      recovery: "—",
      rqd: "—",
      qualifying,
      total: piecesCm.length,
      oversized: true,
    };
  }

  return {
    recovery: pct(total),
    rqd: pct(
      piecesCm
        .filter((piece) => piece >= RQD_MIN_PIECE_CM)
        .reduce((sum, piece) => sum + piece, 0)
    ),
    qualifying,
    total: piecesCm.length,
    oversized: false,
  };
}

function formatValue(value: number | string | null | undefined): string {
  return value === null || value === undefined || value === ""
    ? "—"
    : String(value);
}

function statusLabel(status?: string | null): string {
  if (!status) return "—";
  return status.charAt(0) + status.slice(1).toLowerCase();
}

function asText(value: number | string | null | undefined): string {
  return value === null || value === undefined ? "" : String(value);
}

function parseNumeric(raw: string): number | null {
  const trimmed = raw.trim();
  if (trimmed === "") return null;
  const n = Number(trimmed);
  return Number.isFinite(n) ? n : null;
}

function draftFromRecord(record: RockRecord, unit: PieceUnit): RockDraft {
  return {
    depth_from: asText(record.depth_from),
    depth_to: asText(record.depth_to),
    rock_type: asText(record.rock_type),
    lift_no: asText(record.lift_no),
    // Stored in centimetres; show them in whatever unit is on screen.
    pieces: (record.pieces ?? []).map((piece) => fromCentimetres(Number(piece), unit)),
  };
}

function isBlank(draft: RockDraft): boolean {
  return (
    draft.depth_from.trim() === "" &&
    draft.depth_to.trim() === "" &&
    draft.rock_type.trim() === "" &&
    draft.lift_no.trim() === "" &&
    draft.pieces.every((piece) => piece.trim() === "")
  );
}

/** Validate a draft and convert it to the API shape. Returns an error string
    when something is wrong. The server validates again; this only gives
    immediate feedback. */
function toRow(draft: RockDraft, unit: PieceUnit): RockRow | string {
  const depthFrom = parseNumeric(draft.depth_from);
  const depthTo = parseNumeric(draft.depth_to);

  if (depthFrom === null || depthTo === null) {
    return "Run Depth From and Run Depth To are required.";
  }
  if (depthFrom < 0) {
    return "Run Depth From cannot be negative.";
  }
  if (depthTo <= depthFrom) {
    return "Run Depth To must be greater than Run Depth From.";
  }
  if (draft.rock_type.trim() === "") {
    return "Type of Rock is required.";
  }

  // Blank boxes are skipped rather than counted as zero-length pieces, so
  // clicking "+" and leaving it alone does not invent data.
  const pieces: number[] = [];
  for (let i = 0; i < draft.pieces.length; i += 1) {
    const raw = draft.pieces[i].trim();
    if (raw === "") continue;

    const value = Number(raw);
    if (!Number.isFinite(value)) {
      return `Block Number ${i + 1} must be a number.`;
    }
    if (value < 0) {
      return `Block Number ${i + 1} cannot be negative.`;
    }
    pieces.push(value);
  }

  if (draft.pieces.length > MAX_PIECES) {
    return `A run cannot have more than ${MAX_PIECES} pieces.`;
  }

  // The same impossible case the server rejects, caught here so the user is
  // told before they submit rather than after.
  const totalCm = pieces.reduce(
    (sum, piece) => sum + (unit === "m" ? piece * CM_PER_M : piece),
    0
  );
  const runCm = (depthTo - depthFrom) * CM_PER_M;
  if (totalCm > runCm) {
    // Show both figures in the unit the user is actually typing in.
    const totalShown = unit === "m" ? totalCm / CM_PER_M : totalCm;
    return `Pieces total ${roundForMessage(totalShown)} ${unit}, but the run is only ${roundForMessage(runCm / CM_PER_M)} m long.`;
  }

  return {
    depth_from: depthFrom,
    depth_to: depthTo,
    rock_type: draft.rock_type.trim(),
    lift_no: draft.lift_no.trim() === "" ? null : draft.lift_no.trim(),
    pieces,
    piece_unit: unit,
  };
}

/** Show the offending total in the unit the user typed it in. */
function roundForMessage(value: number): string {
  return String(Math.round(value * 100) / 100);
}

interface RockFieldsProps {
  draft: RockDraft;
  onChange: (field: keyof RockDraft, value: string) => void;
  onPieces: (pieces: string[]) => void;
  pieceUnit: PieceUnit;
  disabled?: boolean;
  /** Row this draft is rendered as, for keyboard navigation. */
  rowIndex?: number;
  onKeyDown?: (event: React.KeyboardEvent<HTMLInputElement>, cell: RockCell) => void;
}

/** The editable cells, shared by the entry grid and inline edit so the two can
    never drift apart. */
function RockFieldCells({
  draft,
  onChange,
  onPieces,
  pieceUnit,
  disabled,
  rowIndex,
  onKeyDown,
}: RockFieldsProps) {
  const metrics = previewMetrics(draft, pieceUnit);

  // Every editable box is tagged so a keystroke can find its neighbours.
  // rowIndex is absent for the inline-edit row, which navigates on its own.
  const tag = (col: number, piece = NO_PIECE) =>
    rowIndex === undefined ? undefined : cellKey(rowIndex, col, piece);
  const handleKey = (event: React.KeyboardEvent<HTMLInputElement>, cell: RockCell) => {
    if (rowIndex !== undefined) {
      cell.row = rowIndex;
    }
    onKeyDown?.(event, cell);
  };

  const COL: Record<"depth_from" | "depth_to" | "rock_type" | "lift_no", number> = {
    depth_from: 0,
    depth_to: 1,
    rock_type: 2,
    lift_no: 3,
  };

  const num = (field: "depth_from" | "depth_to", step: string) => (
    <input
      className="modal-input spt-inline-input"
      type="number"
      inputMode="decimal"
      step={step}
      min="0"
      data-cell={tag(COL[field])}
      aria-label={`Run Depth ${field === "depth_from" ? "From" : "To"}`}
      value={draft[field]}
      disabled={disabled}
      onChange={(e) => onChange(field, e.target.value)}
      onKeyDown={(e) => handleKey(e, { row: 0, col: COL[field], piece: NO_PIECE })}
    />
  );

  const text = (field: "rock_type" | "lift_no") => (
    <input
      className="modal-input spt-inline-input"
      type="text"
      data-cell={tag(COL[field])}
      aria-label={field === "rock_type" ? "Type of Rock" : "Lift Number"}
      value={draft[field]}
      disabled={disabled}
      onChange={(e) => onChange(field, e.target.value)}
      onKeyDown={(e) => handleKey(e, { row: 0, col: COL[field], piece: NO_PIECE })}
    />
  );

  return (
    <>
      <td>{num("depth_from", "0.01")}</td>
      <td>{num("depth_to", "0.01")}</td>

      {/* Derived, so shown, never typed. */}
      <td className="num" data-label="Recovery (%)">
        <span className="rock-derived" title={`Sum of ${metrics.total} piece(s)`}>
          {metrics.recovery}
        </span>
      </td>
      <td className="num" data-label="RQD (%)">
        <span
          className="rock-derived"
          title={`${metrics.qualifying} piece(s) at least ${RQD_MIN_PIECE_CM} cm`}
        >
          {metrics.rqd}
        </span>
      </td>

      <td>{text("rock_type")}</td>
      <td>{text("lift_no")}</td>

      <td data-label={`Pieces (${pieceUnit})`}>
        <div className="rock-pieces">
          {draft.pieces.map((piece, index) => (
            <div className="rock-piece" key={index}>
              <span className="rock-piece-label">Block {index + 1}</span>
              <input
                className="modal-input spt-inline-input rock-piece-input"
                type="number"
                inputMode="decimal"
                step="0.1"
                min="0"
                data-cell={tag(PIECE_COLUMN, index)}
                aria-label={`Block Number ${index + 1} length in ${pieceUnit}`}
                value={piece}
                disabled={disabled}
                onChange={(e) => {
                  const next = [...draft.pieces];
                  next[index] = e.target.value;
                  onPieces(next);
                }}
                onKeyDown={(e) =>
                  handleKey(e, { row: 0, col: PIECE_COLUMN, piece: index })
                }
              />
              <button
                type="button"
                className="btn btn-sm rock-piece-remove"
                aria-label={`Remove Block Number ${index + 1}`}
                disabled={disabled}
                onClick={() =>
                  onPieces(draft.pieces.filter((_, i) => i !== index))
                }
              >
                &times;
              </button>
            </div>
          ))}

          <button
            type="button"
            className="btn btn-sm rock-piece-add"
            disabled={disabled || draft.pieces.length >= MAX_PIECES}
            onClick={() => onPieces([...draft.pieces, ""])}
          >
            + Add piece
          </button>

          {metrics.oversized && (
            <span className="rock-piece-warning">
              Pieces are longer than this run.
            </span>
          )}
        </div>
      </td>
    </>
  );
}

export function RockModule({ projectId, locaId }: RockModuleProps) {
  const { user } = useAuth();
  const isAdmin = user?.role === "admin";

  const [records, setRecords] = useState<RockRecord[]>([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);

  const [pending, setPending] = useState<RockPendingRecord[]>([]);
  const [pendingLoading, setPendingLoading] = useState(false);
  const [reviewError, setReviewError] = useState<string | null>(null);

  // Entry grid: NEW records only. Editing an existing record is inline.
  const [entryOpen, setEntryOpen] = useState(false);

  // What the Block Number boxes are typed in. Centimetres by default, which
  // is what the 10 cm RQD threshold and the stored values both assume.
  const [pieceUnit, setPieceUnit] = useState<PieceUnit>("cm");

  const [gridRows, setGridRows] = useState<RockDraft[]>(() =>
    Array.from({ length: INITIAL_GRID_ROWS }, () => ({ ...EMPTY_DRAFT }))
  );
  // Keyboard navigation needs to find inputs in the live DOM, and needs the
  // row count as it was when a keystroke was handled (not after a re-render).
  const gridRef = useRef<HTMLDivElement | null>(null);
  // The inline-edit row lives in the submitted-records table, not in
  // #rock-entry-grid, so gridRef cannot see it. A second ref keeps the two
  // lookups separate instead of widening one query to the whole document.
  const inlineRef = useRef<HTMLTableElement | null>(null);
  const gridRowsRef = useRef(gridRows);
  gridRowsRef.current = gridRows;
  const [submitting, setSubmitting] = useState(false);
  const [submitError, setSubmitError] = useState<string | null>(null);

  // Same contract as the SPT grid: rows with anything typed in them live only
  // in this component, and the workspace unmounts it on a tab change.
  // EMPTY_DRAFT pieces are [] and empty strings, so a pristine grid compares
  // clean against it.
  const hasUnsavedRockRows = useMemo(
    () =>
      gridRows.some(
        (draft) =>
          draft.depth_from.trim() !== "" ||
          draft.depth_to.trim() !== "" ||
          draft.rock_type.trim() !== "" ||
          draft.lift_no.trim() !== "" ||
          draft.pieces.some((piece) => piece.trim() !== "")
      ),
    [gridRows]
  );

  useUnsavedChanges(
    "rock-grid",
    "Rock entry grid",
    hasUnsavedRockRows && !submitting
  );

  const [editingDepth, setEditingDepth] = useState<number | null>(null);
  const [editDraft, setEditDraft] = useState<RockDraft | null>(null);
  const [savingEdit, setSavingEdit] = useState(false);
  const [editError, setEditError] = useState<string | null>(null);

  const [deleteTarget, setDeleteTarget] = useState<RockRecord | null>(null);
  const [deleting, setDeleting] = useState(false);
  const [deleteError, setDeleteError] = useState<string | null>(null);

  const [diffTarget, setDiffTarget] = useState<RockPendingRecord | null>(null);
  const [diffData, setDiffData] = useState<AuditHistory | null>(null);
  const [diffLoading, setDiffLoading] = useState(false);
  const [diffError, setDiffError] = useState<string | null>(null);

  async function loadRecords() {
    try {
      setLoading(true);
      setError(null);
      setRecords(await getRockRecords(projectId, locaId));
    } catch (err) {
      console.error("Failed to load Rock records:", err);
      setError(err instanceof Error ? err.message : "Unable to load Rock data.");
    } finally {
      setLoading(false);
    }
  }

  async function loadPending() {
    if (!isAdmin) return;
    try {
      setPendingLoading(true);
      setPending(await getPendingRockRecords(projectId, locaId));
    } catch (err) {
      console.error("Failed to load pending Rock records:", err);
    } finally {
      setPendingLoading(false);
    }
  }

  useEffect(() => {
    loadRecords();
    loadPending();
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [projectId, locaId, isAdmin]);

  // ------------------------------------------------------------------
  // New records (entry grid)
  // ------------------------------------------------------------------
  function setGridField(index: number, field: keyof RockDraft, value: string) {
    setGridRows((rows) =>
      rows.map((row, i) => (i === index ? { ...row, [field]: value } : row))
    );
  }

  function addGridRow() {
    setGridRows((rows) => [...rows, { ...EMPTY_DRAFT }]);
  }

  function setGridPieces(index: number, pieces: string[]) {
    setGridRows((rows) =>
      rows.map((row, i) => (i === index ? { ...row, pieces } : row))
    );
  }

  /** Converting the boxes must convert what is in them, not reinterpret it:
      the same lengths, written in the other unit. */
  function convertDraftPieces(pieces: string[], from: PieceUnit, to: PieceUnit): string[] {
    if (from === to) return pieces;
    return pieces.map((piece) => {
      const cm = toCentimetres(piece, from);
      return cm === null ? piece : fromCentimetres(cm, to);
    });
  }

  function changePieceUnit(next: PieceUnit) {
    setGridRows((rows) =>
      rows.map((row) => ({
        ...row,
        pieces: convertDraftPieces(row.pieces, pieceUnit, next),
      }))
    );
    setEditDraft((draft) =>
      draft
        ? {
            ...draft,
            pieces: convertDraftPieces(draft.pieces, pieceUnit, next),
          }
        : draft
    );
    setPieceUnit(next);
  }

  // ------------------------------------------------------------------
  // Keyboard navigation (Excel-style)
  // ------------------------------------------------------------------
  /**
   * How many Block Number boxes each row has right now. The navigation
   * helpers need this shape, not the drafts themselves.
   */
  function pieceCounts(): number[] {
    return gridRows.map((draft) => draft.pieces.length);
  }

  function focusInlineCell(cell: RockCell | null): boolean {
    if (!cell) return false;
    const input = inlineRef.current?.querySelector<HTMLInputElement>(
      `[data-cell="${cellKey(cell.row, cell.col, cell.piece)}"]`
    );
    if (!input || input.disabled) return false;
    input.focus();
    input.select();
    return true;
  }

  /**
   * Keyboard navigation for the inline-edit row of an already submitted
   * record.
   *
   * Deliberately NOT handleRockKeyDown. That handler belongs to the entry
   * grid: its Enter/ArrowDown falls through to growGridAndFocus, so reusing
   * it here would append a fresh row to the entry grid while the engineer was
   * editing a record they had already submitted, and its Escape clears a grid
   * row. This row is one row with nowhere above or below, so navigation is
   * horizontal only and stops at the edges instead of growing anything.
   */
  /** Block boxes in the row currently being edited. */
  function draftPieceCount(): number {
    return editDraft?.pieces.length ?? 0;
  }

  function handleInlineKeyDown(
    event: React.KeyboardEvent<HTMLInputElement>,
    cell: RockCell
  ) {
    if (event.metaKey || event.ctrlKey || event.altKey) return;

    const counts: PieceCounts = [draftPieceCount()];

    if (event.key === "Tab") {
      event.preventDefault();
      const target = event.shiftKey
        ? previousInReadingOrder(counts, cell)
        : nextInReadingOrder(counts, cell);
      focusInlineCell(target);
      return;
    }

    // Same rule as the entry grid: sideways arrows move the caret inside a
    // value, and only take over at the very edge of the text.
    if (event.key === "ArrowLeft" || event.key === "ArrowRight") {
      const el = event.currentTarget;
      if (event.key === "ArrowLeft" && caretAtStart(el)) {
        event.preventDefault();
        focusInlineCell(previousInReadingOrder(counts, cell));
      } else if (event.key === "ArrowRight" && caretAtEnd(el)) {
        event.preventDefault();
        focusInlineCell(nextInReadingOrder(counts, cell));
      }
    }
  }

  function focusRockCell(cell: RockCell | null): boolean {
    if (!cell) return false;
    const input = gridRef.current?.querySelector<HTMLInputElement>(
      `[data-cell="${cellKey(cell.row, cell.col, cell.piece)}"]`
    );
    if (!input || input.disabled) return false;
    input.focus();
    // Select the existing value so typing over it replaces it, which is
    // what a spreadsheet does when you move onto a filled cell.
    input.select();
    return true;
  }

  /** Tab or Enter off the end of the grid: add a row and continue into it. */
  function growGridAndFocus(col: number, piece: number) {
    setGridRows((rows) => [...rows, { ...EMPTY_DRAFT }]);
    const next = gridRowsRef.current.length;
    requestAnimationFrame(() =>
      focusRockCell({ row: next, col, piece })
    );
  }

  function handleRockKeyDown(
    event: React.KeyboardEvent<HTMLInputElement>,
    cell: RockCell
  ) {
    // Anything with a modifier is the browser's business (Shift+Tab,
    // Alt+Arrow, Ctrl+Backspace to clear a word).
    if (event.metaKey || event.ctrlKey || event.altKey) return;

    const counts = pieceCounts();

    if (event.key === "Enter" || event.key === "ArrowDown") {
      event.preventDefault();
      const target = cellBelow(counts, cell);
      if (focusRockCell(target)) return;
      growGridAndFocus(cell.col, cell.piece);
      return;
    }

    if (event.key === "ArrowUp") {
      event.preventDefault();
      focusRockCell(cellAbove(counts, cell));
      return;
    }

    if (event.key === "Tab") {
      event.preventDefault();
      const target = event.shiftKey
        ? previousInReadingOrder(counts, cell)
        : nextInReadingOrder(counts, cell);
      if (focusRockCell(target)) return;
      if (event.shiftKey) return;
      growGridAndFocus(0, NO_PIECE);
      return;
    }

    if (event.key === "Escape") {
      event.preventDefault();
      clearGridRow(cell.row);
      return;
    }

    // Left/right stay sideways so a value already keyed can be corrected
    // with the caret. They only take over at the very edge of the text.
    if (event.key === "ArrowLeft" || event.key === "ArrowRight") {
      const el = event.currentTarget;
      // See gridKeyboard: the depth and Block Number boxes are type="number",
      // where selectionStart is null.
      const atStart = caretAtStart(el);
      const atEnd = caretAtEnd(el);

      if (event.key === "ArrowLeft" && atStart) {
        event.preventDefault();
        const target = previousInReadingOrder(counts, cell);
        if (focusRockCell(target)) return;
        return;
      }

      if (event.key === "ArrowRight" && atEnd) {
        event.preventDefault();
        const target = nextInReadingOrder(counts, cell);
        if (focusRockCell(target)) return;
        growGridAndFocus(0, NO_PIECE);
      }
    }
  }

  function clearGridRow(index: number) {
    setGridRows((rows) =>
      rows.map((row, i) => (i === index ? { ...EMPTY_DRAFT } : row))
    );
  }

  async function submitGrid() {
    // Blank rows are a frontend-only concept: they never reach the API, so
    // they never create records or consume a Sample ID.
    const populated = gridRows
      .map((draft, index) => ({ draft, index }))
      .filter(({ draft }) => !isBlank(draft));

    if (populated.length === 0) {
      setSubmitError("Enter at least one Rock run.");
      return;
    }

    const rows: RockRow[] = [];
    for (const { draft, index } of populated) {
      const row = toRow(draft, pieceUnit);
      if (typeof row === "string") {
        setSubmitError(`Row ${index + 1}: ${row}`);
        return;
      }
      rows.push(row);
    }

    setSubmitting(true);
    setSubmitError(null);
    try {
      await submitRockRecords(projectId, locaId, rows);
      await loadRecords();
      await loadPending();
      setGridRows(
        Array.from({ length: INITIAL_GRID_ROWS }, () => ({ ...EMPTY_DRAFT }))
      );
      setEntryOpen(false);
    } catch (err) {
      console.error("Failed to submit Rock records:", err);
      setSubmitError(
        err instanceof Error ? err.message : "Unable to submit Rock records."
      );
    } finally {
      setSubmitting(false);
    }
  }

  // ------------------------------------------------------------------
  // Inline row editing
  // ------------------------------------------------------------------
  function startEdit(record: RockRecord) {
    setEditingDepth(record.depth_from);
    setEditDraft(draftFromRecord(record, pieceUnit));
    setEditError(null);
  }

  function cancelEdit() {
    setEditingDepth(null);
    setEditDraft(null);
    setEditError(null);
  }

  async function saveEdit(originalDepth: number) {
    if (!editDraft) return;

    const row = toRow(editDraft, pieceUnit);
    if (typeof row === "string") {
      setEditError(row);
      return;
    }

    setSavingEdit(true);
    setEditError(null);
    try {
      await updateRockRecord(projectId, locaId, originalDepth, row);
      // A non-admin edit goes back to PENDING, so refresh both lists.
      await loadRecords();
      await loadPending();
      setEditingDepth(null);
      setEditDraft(null);
    } catch (err) {
      console.error("Failed to update Rock record:", err);
      setEditError(err instanceof Error ? err.message : "Unable to save changes.");
    } finally {
      setSavingEdit(false);
    }
  }

  // ------------------------------------------------------------------
  // Delete
  // ------------------------------------------------------------------
  async function confirmDelete() {
    if (!deleteTarget) return;
    try {
      setDeleting(true);
      setDeleteError(null);
      await deleteRockRecord(projectId, locaId, deleteTarget.depth_from);
      setDeleteTarget(null);
      await loadRecords();
      if (isAdmin) await loadPending();
    } catch (err) {
      console.error("Failed to delete Rock record:", err);
      setDeleteError(
        err instanceof Error ? err.message : "Unable to delete Rock record."
      );
    } finally {
      setDeleting(false);
    }
  }

  // ------------------------------------------------------------------
  // Admin approval
  // ------------------------------------------------------------------
  async function approveRow(record: RockPendingRecord) {
    try {
      setReviewError(null);
      await approveRockRecord(projectId, locaId, record.depth_from);
      await loadPending();
      await loadRecords();
    } catch (err) {
      console.error("Failed to approve Rock record:", err);
      setReviewError(err instanceof Error ? err.message : "Unable to approve.");
    }
  }

  async function rejectRow(record: RockPendingRecord) {
    const reason = window.prompt("Reason for rejection (optional):", "");
    try {
      setReviewError(null);
      await rejectRockRecord(projectId, locaId, record.depth_from, reason || null);
      await loadPending();
      await loadRecords();
    } catch (err) {
      console.error("Failed to reject Rock record:", err);
      setReviewError(err instanceof Error ? err.message : "Unable to reject.");
    }
  }

  async function openDiff(record: RockPendingRecord) {
    setDiffTarget(record);
    setDiffData(null);
    setDiffError(null);
    setDiffLoading(true);
    try {
      setDiffData(await getAuditSampleHistory(projectId, locaId, record.sample_id));
    } catch (err) {
      console.error("Failed to load sample history:", err);
      setDiffError(err instanceof Error ? err.message : "Unable to load the changes.");
    } finally {
      setDiffLoading(false);
    }
  }

  if (loading && records.length === 0 && !error) {
    return <p className="page-sub">Loading Field Data…</p>;
  }

  if (error) {
    return <p className="page-sub field-error">{error}</p>;
  }

  /**
   * The six columns every Rock view shares, in order.
   *
   * Split out from the Pieces header because its position now differs: the
   * entry grid labels it with the unit being typed in, while the submitted
   * tables place it after Lift No and show a count, with the values spelled
   * out on their own row underneath. RockFieldCells emits the matching seven
   * body cells, so all three views stay column-aligned.
   */
  const headerCellsCore = (
    <>
      <th>Run Depth From (m)</th>
      <th>Run Depth To (m)</th>
      <th>Recovery (%)</th>
      <th>RQD (%)</th>
      <th>Type of Rock</th>
      <th>Lift No</th>
    </>
  );

  return (
    <div>
      <div className="module-toolbar">
        <h3 className="panel-subtitle">Rock</h3>
        <div className="actions">
          <div className="rock-unit-toggle" role="group" aria-label="Piece unit">
            <span className="rock-unit-label">Enter pieces in</span>
            {(["cm", "m"] as PieceUnit[]).map((unit) => (
              <button
                key={unit}
                type="button"
                className={`btn btn-sm ${pieceUnit === unit ? "btn-primary" : ""}`}
                aria-pressed={pieceUnit === unit}
                onClick={() => changePieceUnit(unit)}
              >
                {unit}
              </button>
            ))}
            <span className="cell-dim">
              {pieceUnit === "cm"
                ? "centimetres (RQD counts pieces 10 cm and over)"
                : "metres (converted to cm before storage)"}
            </span>
          </div>

          <button
            type="button"
            className={entryOpen ? "btn btn-sm" : "btn btn-sm btn-primary"}
            onClick={() => setEntryOpen((open) => !open)}
            aria-expanded={entryOpen}
            aria-controls="rock-entry-grid"
          >
            {entryOpen ? "Hide Entry Grid" : "Enter Rock Data"}
          </button>
        </div>
      </div>

      {entryOpen && (
        <div id="rock-entry-grid" className="spt-entry-panel" ref={gridRef}>
          <div className="table-scroll">
            <table className="dtable spt-inline-edit">
              <thead>
                <tr>
                  <th>List No</th>
                  {headerCellsCore}
                  <th>Pieces ({pieceUnit})</th>
                </tr>
              </thead>
              <tbody>
                {gridRows.map((draft, index) => (
                  <tr key={index}>
                    {/* Preview of the position the server will assign once the
                        run is submitted, where the list is ordered by depth. */}
                    <td className="cell-dim" data-label="List No">{index + 1}</td>
                    <RockFieldCells
                      draft={draft}
                      rowIndex={index}
                      pieceUnit={pieceUnit}
                      disabled={submitting}
                      onChange={(field, value) => setGridField(index, field, value)}
                      onPieces={(pieces) => setGridPieces(index, pieces)}
                      onKeyDown={handleRockKeyDown}
                    />
                  </tr>
                ))}
              </tbody>
            </table>
          </div>

          <p className="page-sub">
            Enter or ↓ moves down a column · ↑ moves up · Tab moves left to
            right and on into the Block Numbers · ←/→ move sideways to correct
            a value · Esc clears a row. Left and right only move the caret
            when it is already at the end of what you typed, so you can still
            edit the middle of a number.
          </p>

          {submitError && <p className="page-sub field-error">{submitError}</p>}

          <div className="actions">
            <button type="button" className="btn btn-sm" onClick={addGridRow} disabled={submitting}>
              + Add row
            </button>
            <button
              type="button"
              className="btn btn-sm btn-primary"
              onClick={submitGrid}
              disabled={submitting}
            >
              {submitting ? "Submitting…" : "Submit for approval"}
            </button>
          </div>
        </div>
      )}

      <h3 className="panel-subtitle" style={{ marginTop: "20px" }}>
        Submitted Rock Records
      </h3>

      {editError && <p className="page-sub field-error">{editError}</p>}

      {records.length === 0 ? (
        <div className="empty-state">
          <h3>No Rock data</h3>
          <p>No Rock records have been submitted for this location yet.</p>
        </div>
      ) : (
        <div className="table-scroll table-scroll--no-cards">
          <table
            className="dtable spt-inline-edit"
            ref={inlineRef}
          >
            <thead>
              <tr>
                <th>List No</th>
                {headerCellsCore}
                <th>Pieces</th>
                <th>Status</th>
                <th>Actions</th>
              </tr>
            </thead>
            <tbody>
              {records.map((record) => {
                const isEditing = editingDepth === record.depth_from;

                return (
                  <Fragment key={record.depth_from}>
                  <tr className="rock-record-main">
                    {/* Outside the editing ternary: the number is the same
                        whether or not the row is being edited. */}
                    <td className="cell-dim" data-label="List No">
                      {record.list_no}
                    </td>
                    {isEditing && editDraft ? (
                      <>
                        <RockFieldCells
                          draft={editDraft}
                          rowIndex={0}
                          pieceUnit={pieceUnit}
                          disabled={savingEdit}
                          onKeyDown={handleInlineKeyDown}
                          onChange={(field, value) =>
                            setEditDraft((current) =>
                              current ? { ...current, [field]: value } : current
                            )
                          }
                          onPieces={(pieces) =>
                            setEditDraft((current) =>
                              current ? { ...current, pieces } : current
                            )
                          }
                        />
                        <td>
                          <span className="chip chip-info">Editing…</span>
                        </td>
                        <td>
                          <div className="actions">
                            <button
                              type="button"
                              className="btn btn-sm btn-primary"
                              onClick={() => saveEdit(record.depth_from)}
                              disabled={savingEdit}
                            >
                              {savingEdit ? "Saving…" : "Save"}
                            </button>
                            <button
                              type="button"
                              className="btn btn-sm"
                              onClick={cancelEdit}
                              disabled={savingEdit}
                            >
                              Cancel
                            </button>
                          </div>
                        </td>
                      </>
                    ) : (
                      <>
                        <td className="num" data-label="Run Depth From (m)">{formatValue(record.depth_from)}</td>
                        <td className="num" data-label="Run Depth To (m)">{formatValue(record.depth_to)}</td>
                        <td className="num" data-label="Recovery (%)">{formatValue(record.recovery)}</td>
                        <td className="num" data-label="RQD (%)">{formatValue(record.rqd)}</td>
                        <td data-label="Type of Rock">{formatValue(record.rock_type)}</td>
                        <td data-label="Lift No">{formatValue(record.lift_no)}</td>
                        {/* Count only. The values are spelled out on the
                            strip below -- cramming them into one cell was
                            unreadable once a run had six or seven blocks. */}
                        <td data-label="Pieces" className="cell-dim">
                          {record.pieces && record.pieces.length > 0
                            ? `${record.pieces.length} piece${record.pieces.length === 1 ? "" : "s"}`
                            : "--"}
                        </td>
                        <td data-label="Status">
                          <span className="tab-badge">{statusLabel(record.status)}</span>
                        </td>
                        <td data-label="Actions">
                          <div className="actions">
                            <button
                              type="button"
                              className="btn btn-sm btn-edit"
                              onClick={() => startEdit(record)}
                            >
                              Edit
                            </button>
                            <button
                              type="button"
                              className="btn btn-sm btn-danger"
                              onClick={() => {
                                setDeleteTarget(record);
                                setDeleteError(null);
                              }}
                            >
                              Delete
                            </button>
                          </div>
                        </td>
                      </>
                    )}
                  </tr>

                  {/* Every block on its own full-width row, label above
                      value, wrapping when a run has more than fits. Hidden
                      while editing, because then the Pieces cell above is
                      the editor. */}
                  {!isEditing && record.pieces && record.pieces.length > 0 && (
                    <tr className="rock-record-pieces">
                      <td colSpan={10}>
                        <div className="rock-pieces-flow">
                          {record.pieces.map((piece, index) => (
                            <div className="rock-piece-chip" key={index}>
                              <span className="rock-piece-chip-label">
                                Piece {index + 1}
                              </span>
                              <span className="rock-piece-chip-value">
                                {fromCentimetres(Number(piece), pieceUnit)}{" "}
                                {pieceUnit}
                              </span>
                            </div>
                          ))}
                        </div>
                      </td>
                    </tr>
                  )}
                  </Fragment>
                );
              })}
            </tbody>
          </table>
        </div>
      )}

      {isAdmin && (
        <>
          <h3 className="panel-subtitle" style={{ marginTop: "20px" }}>
            Pending Rock Approvals
          </h3>

          {reviewError && <p className="page-sub field-error">{reviewError}</p>}

          {pendingLoading ? (
            <p className="page-sub">Loading pending approvals…</p>
          ) : pending.length === 0 ? (
            <p className="page-sub">No Rock records awaiting approval.</p>
          ) : (
            <div className="table-scroll table-scroll--no-cards">
              <table className="dtable">
                <thead>
                  <tr>
                    <th>List No</th>
                    <th>Sample ID</th>
                    <th>Run (m)</th>
                    <th>Recovery / RQD (%)</th>
                    <th>Type of Rock</th>
                    <th>Lift No</th>
                    <th>Pieces</th>
                    <th>Submitted By</th>
                    <th>Actions</th>
                  </tr>
                </thead>
                <tbody>
                  {pending.map((record) => (
                    <Fragment key={record.depth_from}>
                    <tr className="rock-record-main">
                      <td className="cell-dim" data-label="List No">{record.list_no}</td>
                      <td className="sample-id-cell" data-label="Sample ID">{record.sample_id}</td>
                      <td className="num" data-label="Run (m)">
                        {formatValue(record.depth_from)} – {formatValue(record.depth_to)}
                      </td>
                      <td className="num" data-label="Recovery / RQD (%)">
                        {formatValue(record.recovery)} / {formatValue(record.rqd)}
                      </td>
                      <td data-label="Type of Rock">{formatValue(record.rock_type)}</td>
                      <td data-label="Lift No">{formatValue(record.lift_no)}</td>
                      <td data-label="Pieces" className="cell-dim">
                        {record.pieces && record.pieces.length > 0
                          ? `${record.pieces.length} piece${record.pieces.length === 1 ? "" : "s"}`
                          : "--"}
                      </td>
                      <td data-label="Submitted By">
                        <div>{record.created_by || "—"}</div>
                        {record.last_edited_by && (
                          <div className="cell-dim" style={{ marginTop: 2 }}>
                            <span className="chip chip-info">Edited</span> by{" "}
                            {record.last_edited_by}
                          </div>
                        )}
                      </td>
                      <td data-label="Actions">
                        <div className="actions">
                          {record.last_edited_by && (
                            <button
                              type="button"
                              className="btn btn-sm"
                              onClick={() => openDiff(record)}
                            >
                              View changes
                            </button>
                          )}
                          <button
                            type="button"
                            className="btn btn-sm btn-primary"
                            onClick={() => approveRow(record)}
                          >
                            Approve
                          </button>
                          <button
                            type="button"
                            className="btn btn-sm"
                            onClick={() => rejectRow(record)}
                          >
                            Reject
                          </button>
                        </div>
                      </td>
                    </tr>

                    {/* Same strip as the submitted table, so a reviewer sees
                        the actual piece lengths before approving. */}
                    {record.pieces && record.pieces.length > 0 && (
                      <tr className="rock-record-pieces">
                        <td colSpan={9}>
                          <div className="rock-pieces-flow">
                            {record.pieces.map((piece, index) => (
                              <div className="rock-piece-chip" key={index}>
                                <span className="rock-piece-chip-label">
                                  Piece {index + 1}
                                </span>
                                <span className="rock-piece-chip-value">
                                  {piece} cm
                                </span>
                              </div>
                            ))}
                          </div>
                        </td>
                      </tr>
                    )}
                    </Fragment>
                  ))}
                </tbody>
              </table>
            </div>
          )}
        </>
      )}

      {deleteTarget && (
        <RockDialog
          title="Delete Rock record"
          onClose={deleting ? undefined : () => setDeleteTarget(null)}
        >
          <p className="page-sub" style={{ marginTop: 0 }}>
            Delete the Rock run{" "}
            <b>
              {formatValue(deleteTarget.depth_from)} –{" "}
              {formatValue(deleteTarget.depth_to)} m
            </b>
            ? This cannot be undone.
          </p>
          {deleteError && <p className="page-sub field-error">{deleteError}</p>}
          <div className="actions" style={{ justifyContent: "flex-end" }}>
            <button
              type="button"
              className="btn"
              onClick={() => setDeleteTarget(null)}
              disabled={deleting}
            >
              Cancel
            </button>
            <button
              type="button"
              className="btn btn-danger"
              onClick={confirmDelete}
              disabled={deleting}
            >
              {deleting ? "Deleting…" : "Delete"}
            </button>
          </div>
        </RockDialog>
      )}

      {diffTarget && (
        <RockDialog title="Changes pending approval" onClose={() => setDiffTarget(null)}>
          <p className="page-sub" style={{ marginTop: 0 }}>
            Sample <b>{diffTarget.sample_id}</b> · run{" "}
            <b>
              {formatValue(diffTarget.depth_from)} – {formatValue(diffTarget.depth_to)} m
            </b>
            {diffTarget.last_edited_by && (
              <>
                {" "}· last edited by <b>{diffTarget.last_edited_by}</b>
              </>
            )}
          </p>

          {diffLoading && <p className="page-sub">Loading changes…</p>}
          {diffError && <p className="page-sub field-error">{diffError}</p>}

          {diffData && !diffLoading && diffData.changes.length === 0 && (
            <p className="page-sub">No field-level changes recorded for this record yet.</p>
          )}

          {diffData && diffData.changes.length > 0 && (
            <div className="table-scroll">
              <table className="dtable">
                <thead>
                  <tr>
                    <th>Field</th>
                    <th>Old value</th>
                    <th>New value</th>
                    <th>Edited by</th>
                    <th>When</th>
                  </tr>
                </thead>
                <tbody>
                  {[...diffData.changes]
                    .sort((a, b) => (b.edited_at ?? "").localeCompare(a.edited_at ?? ""))
                    .map((change, index) => (
                      <tr key={`${change.field}-${change.edited_at}-${index}`}>
                        <td>{change.field ?? "—"}</td>
                        <td>{String(change.old_value ?? "—")}</td>
                        <td>{String(change.new_value ?? "—")}</td>
                        <td>{change.edited_by || "—"}</td>
                        <td>
                          {change.edited_at
                            ? new Date(change.edited_at).toLocaleString()
                            : "—"}
                        </td>
                      </tr>
                    ))}
                </tbody>
              </table>
            </div>
          )}

          <div className="actions" style={{ justifyContent: "flex-end" }}>
            <button type="button" className="btn" onClick={() => setDiffTarget(null)}>
              Close
            </button>
          </div>
        </RockDialog>
      )}
    </div>
  );
}

/** Same modal chrome as the SPT dialogs. `onClose` undefined = busy, so
    Escape / backdrop / the X are inert while a request is in flight. */
function RockDialog({
  title,
  onClose,
  children,
}: {
  title: string;
  onClose?: () => void;
  children: ReactNode;
}) {
  useEffect(() => {
    const onKey = (e: KeyboardEvent) => {
      if (e.key === "Escape" && onClose) onClose();
    };
    window.addEventListener("keydown", onKey);
    return () => window.removeEventListener("keydown", onKey);
  }, [onClose]);

  return (
    <div
      className="modal-backdrop"
      role="presentation"
      onMouseDown={(e) => {
        if (e.target === e.currentTarget && onClose) onClose();
      }}
    >
      <div className="modal spt-diff-modal" role="dialog" aria-modal="true" aria-label={title}>
        <div className="panel-head">
          <h2 className="panel-title">{title}</h2>
          <button
            type="button"
            className="btn"
            onClick={onClose}
            disabled={!onClose}
            aria-label="Close"
          >
            <svg width="12" height="12" viewBox="0 0 12 12" fill="none" aria-hidden="true">
              <path
                d="M2.5 2.5l7 7m0-7l-7 7"
                stroke="currentColor"
                strokeWidth="1.6"
                strokeLinecap="round"
              />
            </svg>
          </button>
        </div>
        <div className="panel-body">{children}</div>
      </div>
    </div>
  );
}
